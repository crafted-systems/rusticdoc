#!/usr/bin/env node
// Writes the HTTP API and CLI reference from the service's own descriptions.
//   node scripts/generate-reference.mjs           regenerate
//   node scripts/generate-reference.mjs --check   fail if anything is stale
// The CLI help comes from IMAGE (default rusticdoc:site).
import { execFileSync } from 'node:child_process';
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.includes('--check');
const image = process.env.IMAGE ?? 'rusticdoc:site';
const spec = JSON.parse(readFileSync(join(root, '../openapi.json'), 'utf8'));
const reference = join(root, 'src/content/docs/docs/reference');
const NOTICE = '<!-- Generated by scripts/generate-reference.mjs. Do not edit. -->';

// The description marks these as required because of how the forms are
// declared, but the service accepts a request without them.
const notRequired = {
  RenderForm: ['template', 'files'],
};

// The description uses the Rust field names here; the service reads these.
const renamed = {
  user_password: 'userPassword',
  owner_password: 'ownerPassword',
};

const TAGS = {
  render: { title: 'Render', order: 1 },
  convert: { title: 'Convert', order: 2 },
  templates: { title: 'Stored templates', order: 3 },
  fonts: { title: 'Fonts', order: 4 },
  pdf: { title: 'PDF operations', order: 5 },
  'pdf-forms': { title: 'PDF forms', order: 6 },
  jobs: { title: 'Background jobs', order: 7 },
  service: { title: 'Service', order: 8 },
};

const stale = [];
function write(path, text) {
  if (check) {
    if (!existsSync(path) || readFileSync(path, 'utf8') !== text) stale.push(path);
    return;
  }
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, text);
}

const resolve = (s) => (s?.$ref ? spec.components.schemas[s.$ref.split('/').pop()] : s);
const refName = (s) => s?.$ref?.split('/').pop();
const cell = (text) => (text ?? '').replace(/\s*\n\s*/g, ' ').replace(/\|/g, '\\|');

function typeOf(schema) {
  const s = resolve(schema);
  if (!s) return 'any';
  if (schema?.$ref) return refName(schema);
  if (s.format === 'binary') return 'file';
  if (s.type === 'array') return s.items?.format === 'binary' ? 'files' : `array of ${typeOf(s.items)}`;
  if (Array.isArray(s.type)) return s.type.filter((t) => t !== 'null').join(', ');
  if (s.oneOf || s.anyOf) return (s.oneOf ?? s.anyOf).map(typeOf).filter((t) => t !== 'null').join(', ');
  if (s.type) return s.type;
  return 'JSON';
}

function fieldTable(schema, name) {
  const s = resolve(schema);
  const props = Object.entries(s?.properties ?? {});
  if (!props.length) return '';
  const required = new Set((s.required ?? []).filter((f) => !notRequired[name]?.includes(f)));
  const rows = props
    .sort(([a], [b]) => Number(required.has(b)) - Number(required.has(a)) || a.localeCompare(b))
    .map(([field, v]) => `| \`${renamed[field] ?? field}\` | ${cell(typeOf(v))} | ${required.has(field) ? 'Yes' : 'No'} | ${cell(resolve(v)?.description)} |`);
  return `| Field | Type | Required | Description |\n|---|---|---|---|\n${rows.join('\n')}\n`;
}

function securityLine(op) {
  const sec = op.security ?? spec.security;
  if (!sec?.length || sec.every((s) => !Object.keys(s).length)) return 'Open: no credentials needed.';
  return 'Needs credentials, if any are configured.';
}

function operation(method, path, op) {
  const out = [`## ${method.toUpperCase()} ${path}`, '', op.summary ?? '', ''];
  if (op.description) out.push(op.description.replace(/\s*\n\s*/g, ' '), '');
  out.push(securityLine(op), '');
  const params = (op.parameters ?? []).filter(Boolean);
  if (params.length) {
    out.push('### Parameters', '', '| Name | In | Required | Description |', '|---|---|---|---|');
    for (const p of params) out.push(`| \`${p.name}\` | ${p.in} | ${p.required ? 'Yes' : 'No'} | ${cell(p.description)} |`);
    out.push('');
  }
  const body = op.requestBody?.content;
  if (body) {
    const [type, media] = Object.entries(body)[0];
    const table = fieldTable(media.schema, refName(media.schema));
    out.push('### Request', '', `\`${type}\``, '');
    if (table) out.push(table);
  }
  out.push('### Responses', '', '| Status | Meaning | Body |', '|---|---|---|');
  for (const [status, r] of Object.entries(op.responses ?? {})) {
    const media = Object.entries(r.content ?? {})[0];
    const bodyType = media ? (media[1].schema ? typeOf(media[1].schema) : media[0]) : '';
    const schemaName = refName(media?.[1]?.schema);
    const shown = schemaName && schemaName !== 'BinaryFile' ? `[\`${schemaName}\`](/docs/reference/api/schemas/#${schemaName.toLowerCase()})` : schemaName === 'BinaryFile' ? 'File' : cell(bodyType);
    out.push(`| ${status} | ${cell(r.description)} | ${shown} |`);
  }
  out.push('');
  return out.join('\n');
}

const byTag = {};
for (const [path, item] of Object.entries(spec.paths)) {
  for (const [method, op] of Object.entries(item)) {
    if (typeof op !== 'object' || !op.responses) continue;
    (byTag[op.tags?.[0]] ??= []).push([method, path, op]);
  }
}

const tagDescription = Object.fromEntries((spec.tags ?? []).map((t) => [t.name, t.description]));
const rank = (m) => ['get', 'post', 'put', 'delete'].indexOf(m);
for (const [tag, ops] of Object.entries(byTag)) {
  const meta = TAGS[tag];
  if (!meta) throw new Error(`no title for tag ${tag}`);
  ops.sort((a, b) => a[1].localeCompare(b[1]) || rank(a[0]) - rank(b[0]));
  const text = `---
title: ${meta.title}
description: ${JSON.stringify(`${tagDescription[tag] ?? meta.title}.`)}
sidebar:
  order: ${meta.order}
---

${NOTICE}

${ops.map(([m, p, o]) => operation(m, p, o)).join('\n')}`;
  write(join(reference, 'api', `${tag}.md`), text);
}

const objects = Object.entries(spec.components.schemas)
  .filter(([name, s]) => !name.endsWith('Form') && s.properties)
  .sort(([a], [b]) => a.localeCompare(b));
write(join(reference, 'api', 'schemas.md'), `---
title: Response bodies
description: The JSON objects the API returns.
sidebar:
  order: 8
---

${NOTICE}

${objects.map(([name, s]) => `## ${name}\n\n${s.description ? cell(s.description) + '\n\n' : ''}${fieldTable({ $ref: `#/components/schemas/${name}` }, name)}`).join('\n')}`);

const overview = Object.entries(TAGS)
  .filter(([tag]) => byTag[tag])
  .map(([tag, meta]) => `- [${meta.title}](/docs/reference/api/${tag}/): ${tagDescription[tag] ?? ''}`)
  .join('\n');
write(join(reference, 'api', 'index.md'), `---
title: HTTP API
description: Every route on /v1, generated from the OpenAPI description the service publishes.
sidebar:
  label: Overview
  order: 0
---

${NOTICE}

This reference is generated from the service's OpenAPI ${spec.openapi} description, version ${spec.info.version}. The same description is at [\`/openapi.json\`](/openapi.json) on this site and on your own service.

Requests are multipart forms unless a route says otherwise. Send credentials with \`X-Api-Key\` or \`Authorization: Bearer\`, or use basic auth, as [Authentication](/docs/guides/authentication/) explains. Failures are JSON, as [Errors](/docs/reference/errors/) describes.

${overview}
`);
if (!check) copyFileSync(join(root, '../openapi.json'), join(root, 'public/openapi.json'));
else if (readFileSync(join(root, '../openapi.json'), 'utf8') !== readFileSync(join(root, 'public/openapi.json'), 'utf8')) stale.push('public/openapi.json');

// The CLI: every command's own --help. SKIP_CLI leaves it out where there is no image.
function help(args) {
  return execFileSync('docker', ['run', '--rm', '--entrypoint', 'rusticdoc', image, ...args, '--help'], { encoding: 'utf8' }).trimEnd();
}
function commands(text) {
  const section = text.split(/^Commands:$/m)[1]?.split(/^\S/m)[0] ?? '';
  return [...section.matchAll(/^ {2}([a-z][a-z0-9-]*)/gm)].map((m) => m[1]).filter((c) => c !== 'help');
}
function document(args, depth) {
  const text = help(args);
  const heading = `${'#'.repeat(depth)} ${args.length ? `rusticdoc ${args.join(' ')}` : 'rusticdoc'}`;
  const parts = [`${heading}\n\n\`\`\`text\n${text}\n\`\`\`\n`];
  for (const c of commands(text)) parts.push(document([...args, c], depth + 1));
  return parts.join('\n');
}
function writeCli() {
  const version = execFileSync('docker', ['run', '--rm', '--entrypoint', 'rusticdoc', image, '--version'], { encoding: 'utf8' }).trim();
write(join(reference, 'cli.md'), `---
title: CLI
description: Every rusticdoc command and option, from the binary's own help.
---

${NOTICE}

This is the help of \`${version}\`. The CLI is the same binary as the service. See [Install](/docs/start/install/) for how to run it.

${document([], 2)}`);
}
if (!process.env.SKIP_CLI) writeCli();

if (check && stale.length) {
  console.error(`Out of date, run npm run reference:\n${stale.join('\n')}`);
  process.exit(1);
}
console.log(check ? 'reference is current' : 'reference written');
